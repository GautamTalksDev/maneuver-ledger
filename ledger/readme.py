"""The README's results block, generated from out/summary.json so it can never drift.

The block sits between two marker lines in README.md. `python -m ledger.pipeline all`
rewrites it; tests/test_readme.py fails if the README and the summary disagree.
"""
import re

START = "<!-- results:start (generated by ledger/readme.py from out/summary.json; do not edit) -->"
END = "<!-- results:end -->"


def _pct(x):
    return f"{x * 100:.0f}%"


def block(s):
    f, b, r, t, c = s["fcc"], s["bound"], s["rates"], s["threshold"], s["coverage"]
    row16 = next(x for x in b["rows"] if x["dv_cm_s"] == 16)
    inj16 = next(x for x in b["injection"] if x["dv_cm_s"] == 16)
    inj10 = next(x for x in b["injection"] if x["dv_cm_s"] == 10)
    syn16 = next(x for x in s["synthetic"]["by_dv"] if x["dv_cm_s"] == 16)
    gen1_share = row16["max_share_of_gen1"]
    win = next(x for x in s["held_out"]["by_launch_age"] if x["label"] == "launched in the window")
    old = next(x for x in s["held_out"]["by_launch_age"] if x["label"] == "over a year before")
    ag = s["agreement"]["all"]
    lines = [
        START,
        "",
        "| | |",
        "|---|---|",
        f"| Filed by SpaceX (FCC, {f['period_start']} to {f['period_end']}) | {f['total']:,} avoidance manoeuvres "
        f"({f['gen1']:,} Gen 1 + {f['gen2']:,} Gen 2) |",
        f"| Per satellite per year | {f['combined_rate']:.1f} (fleet of {f['satcat_mean_fleet']:,.0f} from CelesTrak SATCAT); "
        f"stated: about {f['gen1_rate_stated']} Gen 1, about {f['gen2_rate_stated']} Gen 2 |",
        f"| Public data used | {c['first_epoch'][:10]} to {c['last_epoch'][:10]}, {c['headline_satellites']:,} on-station "
        f"satellites, {c['headline_exposure_years']:.1f} satellite-years tested |",
        f"| Detection threshold | {t['m']} m of semi-major axis: about {t['dv_cm_s_at_470km']:.1f} cm/s at 470 km, "
        f"{b['threshold_dv_cm_s']:.1f} cm/s in the low-drag band; false alarms on passive "
        f"debris {t['far_per_year']:.2f} per object-year (95% upper {t['far_upper95']:.2f}) |",
        f"| Steps above it, 400 to 600 km | drag make-up {r['drag make-up']['rate']:.1f} per sat-year; avoidance-like "
        f"{r['avoidance-like']['rate']:.1f} ({r['avoidance-like']['lo95']:.1f} to {r['avoidance-like']['hi95']:.1f}) |",
        f"| Low-drag band {b['band']} | {b['steps']} steps of any kind in {b['exposure_years']:.1f} satellite-years: at most "
        f"{b['steps_upper95_per_year']:.2f} per sat-year (conservative 95% bound, see docs/METHODS.md section 7) |",
        f"| Recall in that band | {inj16['recall'] * 100:.0f}% at 16 cm/s, {inj10['recall'] * 100:.0f}% at 10 cm/s "
        f"(burns injected into real histories) |",
        f"| Burns of 16 cm/s or more | at most {row16['max_rate']:.1f} per sat-year, {_pct(gen1_share)} of the lower filed "
        f"rate |",
        f"| Synthetic exam at 16 cm/s | precision {syn16['precision'] * 100:.1f}%, recall {syn16['recall'] * 100:.1f}% |",
        f"| Held out: launched during the window | {win['raising']} of {win['raising'] + win['on-station'] + win['descending'] + win['short']} "
        f"labelled raising; launched over a year before: {old['raising']} raising of "
        f"{old['raising'] + old['on-station'] + old['descending'] + old['short']:,} |",
        f"| GP against SupGP, beyond chance | {_pct(ag['beyond_chance'])} (pre-registered line "
        f"{_pct(s['agreement']['pre_registered_line'])}: {'met' if s['agreement']['met'] else 'not met'}) |",
        "",
        f"**Headline:** if the filing-period rate still held, at least {_pct(1 - gen1_share)} of Starlink avoidance "
        f"manoeuvres are smaller than 16 cm/s along track (or leave the orbit's size unchanged), so public element sets "
        f"cannot rebuild the {f['total']:,}. **The {f['total']:,} was not reproduced.**",
        "",
        END,
    ]
    return "\n".join(lines)


def update(readme_path, summary):
    with open(readme_path, encoding="utf-8") as fh:
        text = fh.read()
    new = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda m: block(summary), text, flags=re.S)
    if new != text:
        with open(readme_path, "w", encoding="utf-8") as fh:
            fh.write(new)
    return new
